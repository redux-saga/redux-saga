import { createUnplugin } from 'unplugin'
import { transform, MAYBE_SAGA } from './transform.js'

export { transform }

const SCRIPT_FILE = /\.[cm]?[jt]sx?$/
const NODE_MODULES = /[\\/]node_modules[\\/]/

// A coarse version of the checks below that bundlers with native hook filters (Vite 8, Rolldown,
// Rollup 4.40+) run themselves, so modules that can't contain sagas never cross into JS.
// `transformInclude` still makes the final call. The patterns stick to syntax Rust's regex crate
// understands (`\x00`, not `\0`).
const TRANSFORM_FILTER = {
  id: {
    include: [/\.[cm]?[jt]sx?(?:$|\?)/],
    // eslint-disable-next-line no-control-regex -- matches the `\0` prefix of virtual modules
    exclude: [/^\x00/, NODE_MODULES],
  },
  code: MAYBE_SAGA,
}

// Module ids as forward-slash paths without a query, so `include`/`exclude` strings like
// '/src/sagas/' match on Windows too, where webpack and esbuild hand over backslash paths.
function toFile(id) {
  return id.split('?')[0].replace(/\\/g, '/')
}

function toMatcher(pattern) {
  if (pattern == null) return () => false
  const patterns = Array.isArray(pattern) ? pattern : [pattern]
  return (id) =>
    patterns.some((p) => {
      if (typeof p === 'string') return id.includes(p)
      // A global or sticky RegExp remembers where its last match ended.
      p.lastIndex = 0
      return p.test(id)
    })
}

/**
 * Options:
 * - `include` / `exclude`: string (substring) or RegExp, or arrays of them, matched against
 *   the file path with forward slashes. By default every JS/TS file outside node_modules is
 *   considered.
 * - `useAbsolutePath`: report absolute file names instead of paths relative to `cwd`.
 * - `cwd`: base directory for relative file names. Defaults to Vite's `root` or webpack/Rspack's
 *   `context`, else `process.cwd()`.
 * - `enabled`: force the plugin on or off. By default it runs in Vite unless it is a production
 *   build or server (`isProduction`, so Vitest included), in webpack/Rspack when `mode` is set to
 *   something other than `production`, and elsewhere when `NODE_ENV !== 'production'`.
 */
export const unplugin = createUnplugin((options = {}) => {
  const isIncluded = options.include ? toMatcher(options.include) : () => true
  const isExcluded = toMatcher(options.exclude)
  let enabled = options.enabled ?? process.env.NODE_ENV !== 'production'
  let cwd = options.cwd
  const warnedFiles = new Set()

  // webpack and Rspack set `mode` in their config rather than in NODE_ENV, so
  // `webpack --mode production` must switch the plugin off on its own.
  function fromWebpackLikeCompiler(compiler) {
    const { mode, context } = compiler.options
    // With no `mode` set both bundlers build for production, whatever NODE_ENV says.
    if (options.enabled === undefined) enabled = (mode ?? 'production') !== 'production'
    if (cwd === undefined && context) cwd = context
  }

  return {
    name: 'redux-saga',
    enforce: 'pre',
    transformInclude(id) {
      // `\0`-prefixed ids are virtual modules generated by other plugins.
      if (!enabled || id.startsWith('\0')) return false
      const file = toFile(id)
      if (!SCRIPT_FILE.test(file) || NODE_MODULES.test(file)) return false
      return isIncluded(file) && !isExcluded(file)
    },
    transform: {
      filter: TRANSFORM_FILTER,
      handler(code, id) {
        const file = id.split('?')[0]
        return transform(code, file, {
          cwd,
          useAbsolutePath: options.useAbsolutePath,
          onParseError: (error) => {
            if (warnedFiles.has(file)) return
            warnedFiles.add(file)
            const message = `[redux-saga] skipped ${toFile(file)}, which could not be parsed (${
              error.message
            }). Saga stacks won't show locations for this file; add it to \`exclude\` to silence this warning.`
            if (typeof this?.warn === 'function') this.warn(message)
            else console.warn(message)
          },
        })
      },
    },
    vite: {
      configResolved(config) {
        // `isProduction` rather than `mode`: `vite build --mode staging` is still a production
        // build, and must not ship file paths and source snippets.
        if (options.enabled === undefined) enabled = !config.isProduction
        if (cwd === undefined) cwd = config.root
      },
    },
    webpack: fromWebpackLikeCompiler,
    rspack: fromWebpackLikeCompiler,
  }
})
